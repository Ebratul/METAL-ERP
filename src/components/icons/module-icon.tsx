export interface ModuleIconProps {
  name: string;
  className?: string;
  size?: number;
  strokeWidth?: number;
}

export function ModuleIcon({
  name,
  className,
  size = 18,
  strokeWidth = 1.75,
}: ModuleIconProps) {
  const Icon = ICONS[name] ?? Squircle;
  return (
    <Icon
      className={className}
      size={size}
      strokeWidth={strokeWidth}
      aria-hidden="true"
    />
  );
}

export function hasIcon(name: string): boolean {
  return name in ICONS;
}
